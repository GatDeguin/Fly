import assert from 'node:assert/strict';
import test from 'node:test';
import * as THREE from 'three';
import { createCockpitRayEffects, rayBoxDistance } from '../src/cockpit-rays.js';

test('analytic cockpit rays hit a box without degeneracy at parallel edges', () => {
  const lo = [-1, -1, -1], hi = [1, 1, 1];
  assert.equal(rayBoxDistance([0, 0, 4], [0, 0, -1], lo, hi), 3);
  assert.equal(rayBoxDistance([1, 0, 4], [0, 0, -1], lo, hi), 3);
  assert.equal(rayBoxDistance([1.01, 0, 4], [0, 0, -1], lo, hi), Infinity);
  assert.equal(rayBoxDistance([0, 0, 0], [1, 0, 0], lo, hi), 1);
  assert.equal(rayBoxDistance([0, 0, 4], [0, 0, 1], lo, hi), Infinity);
  assert.equal(rayBoxDistance([0, 0, 0], [0, 0, 0], lo, hi), Infinity);
});

test('deck rays preserve material hooks and transform the live instrument plane into cabin coordinates', () => {
  const cabin = new THREE.Group(), bay = new THREE.Group(), object = new THREE.Object3D();
  cabin.position.set(500, 9753, -114);
  cabin.rotation.y = .8;
  cabin.add(bay);
  bay.position.set(-1.4, -.15, -13.25);
  bay.add(object);
  object.scale.set(1.2, .84, 1);
  const texture = new THREE.Texture(), material = new THREE.MeshPhysicalMaterial();
  const standard = new THREE.MeshStandardMaterial();
  let originalHookRan = false;
  material.onBeforeCompile = shader => { originalHookRan = true; shader.uniforms.existing = { value: 4 }; };
  material.customProgramCacheKey = () => 'existing-shader';
  const effects = createCockpitRayEffects(cabin, { windshield: material, coaming: standard }, { pfd: { object, texture } });
  const shader = { uniforms: {}, fragmentShader: THREE.ShaderLib.physical.fragmentShader };
  material.onBeforeCompile(shader);
  assert.ok(originalHookRan);
  assert.equal(shader.uniforms.existing.value, 4);
  assert.match(material.customProgramCacheKey(), /^existing-shader.*deck-rays/);
  assert.notEqual(material.customProgramCacheKey(), standard.customProgramCacheKey());
  assert.match(shader.fragmentShader, /deckScreenHit/);
  assert.match(shader.fragmentShader, /#include <opaque_fragment>/);
  assert.match(shader.fragmentShader, /#include <tonemapping_fragment>/);
  assert.equal(effects.active, false);
  effects.update({ rayTracing: true, brightness: .7, day: .2 });
  assert.equal(effects.active, true);
  assert.equal(shader.uniforms.deckRayActive.value, 1);
  assert.equal(shader.uniforms.deckPfdImage.value, texture);
  assert.equal(shader.uniforms.deckPfdAvailable.value, 1);
  assert.equal(shader.uniforms.deckNdAvailable.value, 0);
  assert.ok(new THREE.Vector3(-1.4, -.15, -13.25).applyMatrix4(shader.uniforms.deckPfdTransform.value).length() < 1e-9);
  assert.ok(cabin.position.clone().applyMatrix4(shader.uniforms.deckWorldToLocal.value).length() < 1e-9);
  object.scale.x = NaN;
  effects.update({ rayTracing: true });
  assert.equal(shader.uniforms.deckPfdAvailable.value, 0);
  assert.ok(shader.uniforms.deckPfdTransform.value.elements.every(Number.isFinite));
  cabin.visible = false;
  assert.equal(effects.active, false);
  effects.update({ rayTracing: true });
  assert.equal(shader.uniforms.deckRayActive.value, 0);
  cabin.visible = true;
  effects.update({ rayTracing: false });
  assert.equal(effects.active, false);
  material.dispose();
  standard.dispose();
  texture.dispose();
});

test('windshield rain runs without ray tracing and respects reduced motion', () => {
  const cabin = new THREE.Group();
  cabin.position.set(40, 200, -140);
  const windshield = new THREE.MeshPhysicalMaterial(), coaming = new THREE.MeshStandardMaterial();
  const effects = createCockpitRayEffects(cabin, { windshield, coaming });
  const shader = () => ({ uniforms: {}, fragmentShader: THREE.ShaderLib.physical.fragmentShader });
  const wet = shader(), opaque = shader();
  windshield.onBeforeCompile(wet);
  coaming.onBeforeCompile(opaque);
  assert.match(wet.fragmentShader, /deckWindshieldFilm/);
  assert.doesNotMatch(opaque.fragmentShader, /deckWindshieldFilm/);
  effects.update({ rayTracing: false, rain: .7, elapsed: 3, wipers: true, wiperPhase: .37 });
  assert.equal(effects.active, false);
  assert.equal(wet.uniforms.deckRainWetness.value, .7);
  assert.equal(wet.uniforms.deckRainClock.value, 3);
  assert.equal(wet.uniforms.deckWipersOn.value, 1);
  assert.equal(wet.uniforms.deckWiperPhase.value, .37);
  assert.ok(cabin.position.clone().applyMatrix4(wet.uniforms.deckWorldToLocal.value).length() < 1e-9);
  effects.update({ rain: .7, elapsed: 27, reducedMotion: true });
  const frozen = wet.uniforms.deckRainClock.value;
  effects.update({ rain: .7, elapsed: 49, reducedMotion: true });
  assert.equal(wet.uniforms.deckRainClock.value, frozen);
  effects.update({ rain: 0 });
  assert.equal(wet.uniforms.deckRainWetness.value, 0);
  windshield.dispose();
  coaming.dispose();
});
