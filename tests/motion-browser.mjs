import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const html=await fs.readFile('index.html','utf8');
const browser=await chromium.launch({...(process.env.SKYJOURNEY_BROWSER_CHANNEL?{channel:process.env.SKYJOURNEY_BROWSER_CHANNEL}:{}),headless:true});
try{
 const page=await browser.newPage({viewport:{width:1100,height:800}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',r=>r.request().url().startsWith('https://skyjourney.test/')?r.fulfill({status:200,contentType:'text/html',body:html}):r.abort());
 await page.addInitScript(()=>{
  window.hapticCalls=[];
  Object.defineProperty(navigator,'vibrate',{configurable:true,value:pattern=>{window.hapticCalls.push({pattern,at:performance.now()});return true;}});
  window.DeviceOrientationEvent=class{static requestPermission(){return Promise.resolve('granted')}};
  Object.defineProperty(screen.orientation,'angle',{configurable:true,value:0});
  window.sensorReading=(beta,gamma,alpha)=>window.dispatchEvent(Object.assign(new Event('deviceorientation'),{beta,gamma,alpha}));
 });
 await page.goto('https://skyjourney.test/');
 await page.waitForFunction(()=>window.SkyJourney?.state?.flightTime>0);
 await page.locator('#loader').waitFor({state:'detached'});
 await page.evaluate(()=>SkyJourney.action('quality','performance'));
 await page.locator('[data-panel="settings"]').click();
 const invert=page.locator('[data-input="invertMotionY"]');
 assert.equal(await invert.isChecked(),false);
 await page.locator('[data-action="motion"]').filter({hasText:'Phone tilt controls'}).click();
 await page.evaluate(()=>{sensorReading(0,0,0);sensorReading(6,12,12)});
 await page.waitForFunction(()=>SkyJourney.simulation.controls.pitch<-.15&&SkyJourney.simulation.controls.roll>.45);
 const roll=await page.evaluate(()=>SkyJourney.simulation.controls.roll);
 await invert.locator('xpath=ancestor::label').click();
 await page.waitForFunction(()=>SkyJourney.simulation.controls.pitch>.15);
 assert.ok(Math.abs(await page.evaluate(()=>SkyJourney.simulation.controls.roll)-roll)<.02,'inversion leaves sensor roll unchanged');
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('skyjourney-preferences-v1')).settings.invertMotionY),true);
 await page.evaluate(()=>sensorReading(6,12,12));
 const invertX=page.locator('[data-input="invertMotionX"]'),invertZ=page.locator('[data-input="invertMotionZ"]');
 await invertX.locator('xpath=ancestor::label').click();
 await page.waitForFunction(()=>SkyJourney.simulation.controls.roll<-.4&&SkyJourney.simulation.controls.yaw<-.2);
 await invertZ.locator('xpath=ancestor::label').click();
 await page.waitForFunction(()=>SkyJourney.simulation.controls.yaw>.2&&SkyJourney.simulation.controls.pitch>.15);
 assert.equal(await page.evaluate(()=>SkyJourney.snapshot().settings.invertMotionX&&SkyJourney.snapshot().settings.invertMotionZ),true);
 await page.reload();await page.waitForFunction(()=>window.SkyJourney?.state?.flightTime>0);await page.locator('#loader').waitFor({state:'detached'});
 await page.evaluate(()=>SkyJourney.action('quality','performance'));
 await page.locator('[data-panel="settings"]').click();
 assert.equal(await invert.isChecked(),true,'inverted preference survives reload');
 assert.equal(await page.locator('[data-input="invertMotionX"]').isChecked(),true);
 assert.equal(await page.locator('[data-input="invertMotionZ"]').isChecked(),true);
 const haptics=page.locator('[data-input="haptics"]');await haptics.locator('xpath=ancestor::label').click();
 await page.evaluate(()=>hapticCalls.length=0);
 await page.locator('[data-action="hapticTest"]').click();
 assert.ok(await page.evaluate(()=>hapticCalls.some(c=>JSON.stringify(c.pattern)===JSON.stringify([19,60,30]))),'test button sends its own scaled preview pattern');
 await page.locator('[data-panel="settings"]').click();
 await page.evaluate(()=>{hapticCalls.length=0;SkyJourney.action('autopilot',false)});
 await page.locator('#scene canvas').click({position:{x:750,y:250}});
 await page.keyboard.down('a');
 await page.waitForFunction(()=>hapticCalls.some(c=>Array.isArray(c.pattern)&&c.pattern[0]>0));
 await page.keyboard.up('a');
 await page.evaluate(()=>{SkyJourney.action('pause',true);hapticCalls.length=0});
 await page.waitForTimeout(400);
 assert.equal(await page.evaluate(()=>hapticCalls.some(c=>Array.isArray(c.pattern)&&c.pattern.some(n=>n>0))),false,'paused flight emits no pulses');
 await page.evaluate(()=>{SkyJourney.action('pause',false);SkyJourney.action('weather','Thunderstorm');Object.assign(SkyJourney.world.env,{wind:30,rain:1});hapticCalls.length=0});
 await page.waitForFunction(()=>hapticCalls.some(c=>Array.isArray(c.pattern)&&c.pattern.length>=5));
 await page.evaluate(()=>SkyJourney.action('haptics',false));
 assert.equal(await page.evaluate(()=>hapticCalls.at(-1).pattern),0,'disabling haptics cancels motor');
 await page.evaluate(()=>hapticCalls.length=0);await page.waitForTimeout(400);
 assert.equal(await page.evaluate(()=>hapticCalls.some(c=>Array.isArray(c.pattern)&&c.pattern.some(n=>n>0))),false,'disabled flight remains quiet through storm');
 await page.evaluate(()=>SkyJourney.action('resetSettings'));
 assert.equal(await page.evaluate(()=>['invertMotionY','invertMotionX','invertMotionZ'].some(key=>SkyJourney.snapshot().settings[key])),false);
 assert.deepEqual(errors,[]);
 console.log('Game X/Y/Z motion/haptics: inversion, unchanged roll, saved preference, maneuver, storm, pause and motor cancellation pass.');
}finally{await browser.close();}
