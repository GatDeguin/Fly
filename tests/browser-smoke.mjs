import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
await fs.mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({...(process.env.SKYJOURNEY_BROWSER_CHANNEL?{channel:process.env.SKYJOURNEY_BROWSER_CHANNEL}:{}),headless:true});
const page=await browser.newPage({viewport:{width:1600,height:900},acceptDownloads:true});
const errors=[],requests=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});page.on('request',r=>requests.push(r.url()));
await page.route('https://**',r=>r.abort());
await page.goto('http://127.0.0.1:4173/');
try { await page.waitForFunction(()=>window.SkyJourney?.state?.flightTime>0,null,{timeout:45000}); } catch(e) { console.log('Init errors',errors); console.log(await page.locator('body').innerText()); await page.screenshot({path:'artifacts/init-failure.png'}); await browser.close(); throw e; }
await page.evaluate(()=>SkyJourney.action('pause',true));
await page.waitForTimeout(500);
await page.evaluate(()=>document.querySelector('.pause-screen').hidden=true);
await page.screenshot({path:'artifacts/exterior.png'});
console.log('Initial diagnostics',await page.evaluate(()=>SkyJourney.diagnostics));
await page.evaluate(()=>SkyJourney.action('camera','Pilot'));
await page.waitForTimeout(500);
await page.screenshot({path:'artifacts/cockpit.png'});
const savedPosition=await page.evaluate(()=>({...SkyJourney.state.position}));
for(const view of ['Copilot','External','Chase','Side','Front','Left wing','Right wing','Top','Free','Orbit','Cinematic']){
 await page.evaluate(name=>SkyJourney.action('camera',name),view);
 assert.deepEqual(await page.evaluate(()=>({...SkyJourney.state.position})),savedPosition,'camera changes preserve flight position');
}
await page.evaluate(()=>SkyJourney.action('camera','External'));
await page.evaluate(()=>{window.savedQAFlightTime=SkyJourney.state.flightTime;SkyJourney.state.flightTime=61;SkyJourney.action('camera','Cinematic');});
await page.waitForTimeout(100);
assert.equal(await page.evaluate(()=>SkyJourney.aircraft.cabin.visible),true,'cinematic cruise includes the same physical cockpit');
await page.evaluate(()=>{SkyJourney.state.flightTime=window.savedQAFlightTime;SkyJourney.action('camera','External');});
await page.locator('[data-panel="flight"]').click();
await page.locator('[data-input="apHeading"]').fill('220');
await page.locator('[data-input="apHeading"]').press('Tab');
assert.equal(await page.evaluate(()=>SkyJourney.autopilot.heading),220);
await page.locator('[data-input="apAltitude"]').fill('34000');
await page.locator('[data-input="apAltitude"]').press('Tab');
assert.equal(await page.evaluate(()=>SkyJourney.autopilot.altitude),34000);
await page.locator('[data-input="mode"]').selectOption('standard');
assert.equal(await page.evaluate(()=>SkyJourney.simulation.settings.mode),'standard');
await page.locator('[data-panel="flight"]').click();
await page.evaluate(()=>SkyJourney.action('pause',false));
await page.locator('#scene canvas').click({position:{x:800,y:230}});
await page.keyboard.press('p');
assert.equal(await page.evaluate(()=>SkyJourney.autopilot.enabled),false);
await page.keyboard.down('d');await page.waitForFunction(()=>SkyJourney.state.roll>.02,null,{timeout:15000});await page.keyboard.up('d');
assert.ok(Math.abs(await page.evaluate(()=>SkyJourney.state.roll))>.02,'keyboard changes physical bank');
await page.evaluate(()=>SkyJourney.action('brake',true));await page.waitForTimeout(200);
assert.equal(await page.evaluate(()=>SkyJourney.simulation.controls.brake),true,'held touch brake remains active');
await page.evaluate(()=>SkyJourney.action('brake',false));
await page.evaluate(()=>{SkyJourney.action('pause',true);SkyJourney.action('volume',0);SkyJourney.action('save');});
const stateBefore=await page.evaluate(()=>SkyJourney.snapshot());
await page.evaluate(()=>{SkyJourney.action('reset','runway');SkyJourney.action('resume');SkyJourney.action('pause',true);});
assert.ok(Math.abs((await page.evaluate(()=>SkyJourney.state.position.y))-stateBefore.simulation.state.position.y)<5);
assert.equal(await page.evaluate(()=>SkyJourney.snapshot().settings.volume),0,'silent saved flight stays silent');
await page.evaluate(()=>SkyJourney.action('import',{version:1}));
assert.ok(Number.isFinite(await page.evaluate(()=>SkyJourney.state.altitude)),'invalid import preserves valid simulation');
await page.evaluate(()=>{SkyJourney.action('photoMode',true);SkyJourney.action('time',22);});
await page.waitForTimeout(300);
assert.equal(await page.locator('.pause-screen').isVisible(),false,'photo mode permits composition while simulation paused');
assert.ok((await page.evaluate(()=>SkyJourney.world.env.time))>18.7,'time transitions work while paused');
const photo=page.waitForEvent('download');await page.evaluate(()=>SkyJourney.action('photo'));const downloaded=await photo;
await downloaded.saveAs('artifacts/photo-export.png');
assert.ok((await fs.stat('artifacts/photo-export.png')).size>10000);
await page.evaluate(()=>{SkyJourney.action('photoMode',false);SkyJourney.action('reset','cruise');SkyJourney.action('weather','Starry Night');SkyJourney.action('quality','performance');});
await page.waitForTimeout(700);
assert.equal(await page.evaluate(()=>SkyJourney.diagnostics.weather),'Starry Night');
assert.equal(await page.evaluate(()=>SkyJourney.snapshot().settings.quality),'performance');
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
await mobile.goto('http://127.0.0.1:4173/');await mobile.waitForFunction(()=>window.SkyJourney?.state?.flightTime>0);
await mobile.locator('#loader').waitFor({state:'detached'});
await mobile.screenshot({path:'artifacts/mobile-game.png'});
assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth),390,'mobile UI stays inside viewport');
assert.equal(await mobile.locator('.touch-joystick').isVisible(),true);
await mobile.close();
console.log('12 cameras, AP controls, manual flight, touch brake, save/load, invalid import, photo export, weather and mobile UI pass.');
assert.equal(errors.length,0,errors.join('\n'));
assert.ok(requests.every(url=>url.startsWith('http://127.0.0.1:4173')||url.startsWith('data:')||url.startsWith('blob:')),'offline runtime makes no network requests');
console.log('Local boot + both cameras + no JS/shader errors pass.');
await browser.close();

